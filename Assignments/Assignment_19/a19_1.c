void pattern (int iRow ) {
    int i = 0 ; 
    int j = 0 ;

    for( i =1 ; i <= iRow ; i++) {
        for( j = 1 ; j<= i ; j++){
            printf("*\t"); 
        }
        printf("\n"); 

    }
}


////////////////////////////////////////////////////////////////////////////
//
//              Entery point 
//
////////////////////////////////////////////////////////////////////////////


int main(){

    int iValue = 0 ; 

    printf("Enter number of rows : "); 
    if (scanf("%d", &iValue) != 1 ){
        fprintf(stderr, "invalid input") ; 
        return EXIT_FAILURE ; 

    }

    pattern (iValue ) ; 

    return EXIT_SUCCESS ; 

}
